/**
 * src/lib/export/cesvu-export.ts — Export/import of a {@link CesvuDocument}
 * as a self-describing `.cesvu` binary file.
 *
 * ── What this format provides ─────────────────────────────────────────────
 * This module builds and parses a plain `.cesvu` container with no
 * confidentiality — anyone who has the file can read its contents. What IS
 * provided is INTEGRITY: a SHA-256 checksum over the payload lets a reader
 * detect accidental corruption or truncation (e.g. a bad download, a flaky
 * USB drive, a copy interrupted mid-transfer). It is NOT a security
 * boundary — a deliberate attacker can trivially edit the payload and
 * recompute a matching checksum, since nothing is keyed or secret. Do not
 * represent this format as tamper-evident against a motivated adversary;
 * it only guards against accidental bit-rot.
 *
 * ── Format ───────────────────────────────────────────────────────────────
 *   offset   size  field
 *   0        6     magic — '.CESVU'
 *   6        2     version — uint16 BE. This format uses version 2. A
 *                  reader encountering a different version (e.g. v1, a
 *                  distinct file format this build does not read) MUST
 *                  reject it with UNSUPPORTED_VERSION rather than attempt
 *                  to parse it as v2.
 *   8        2     preambleLen — uint16 BE, length in bytes of the
 *                  human-readable preamble that follows
 *   10       P     preamble — UTF-8 plain text, exactly `preambleLen`
 *                  bytes (see {@link DEFAULT_PREAMBLE}). Purely
 *                  informational — a human opening the raw bytes in a text
 *                  editor sees what the file is and is warned not to edit
 *                  it. Not parsed for anything structural.
 *   10+P     2     metaLen — uint16 BE, length in bytes of the metadata
 *                  JSON that follows
 *   12+P     M     metadata — UTF-8 JSON, exactly `metaLen` bytes (see
 *                  {@link CesvuMetadata} / {@link CesvuMetadataSchema})
 *   12+P+M   32    checksum — SHA-256 digest (via Web Crypto's
 *                  `crypto.subtle.digest`) of the payload bytes that follow
 *   44+P+M   *     payload — the CFP1-framed document bytes (unchanged —
 *                  see contract-store.svelte.ts's buildExportPayload)
 *
 * Stack:
 *   - Web Crypto API (`crypto.subtle.digest('SHA-256', …)`) for the
 *     integrity checksum — no WASM, no third-party crypto dependency.
 *   - zod — envelope metadata validation (unchanged from the prior format).
 */

import { z } from 'zod';

// ── Reusable TextEncoder / TextDecoder ─────────────────────────────────

const _encoder = new TextEncoder();
const _decoder = new TextDecoder();

// ── Public constants ──────────────────────────────────────────────────

/** Six ASCII bytes. Bytes 0–5 of every .cesvu file. */
export const MAGIC = _encoder.encode('.CESVU');

/**
 * Current format version. Bytes 6–7 (uint16 BE). A reader encountering a
 * different version MUST reject it with UNSUPPORTED_VERSION rather than
 * attempt to parse it under this version's layout.
 */
export const VERSION = 2 as const;

/**
 * Sanity cap on the metadata JSON length prefix.
 */
export const MAX_METADATA_JSON_LEN = 4096;

/**
 * Largest preamble we'll read or write, in UTF-8 encoded bytes. Bytes 8–9
 * (the `preambleLen` uint16 field) can address up to 65535, but this is a
 * deliberate app-level sanity ceiling. `buildCesvuFile` always writes
 * exactly `preambleBytes.length` bytes (never padded to the cap), so this
 * costs nothing for files with the default (short) preamble.
 */
export const MAX_PREAMBLE_LEN = 4096;

/** 6 (magic) + 2 (version) + 2 (preamble length). Fixed. */
export const FIXED_PREFIX = 10;

/** Length of the SHA-256 integrity checksum field. */
export const CHECKSUM_LEN = 32;

/**
 * The canonical preamble, written into every `.cesvu` file this build
 * produces unless the caller supplies their own. Purely informational —
 * it exists so a human who opens the raw file bytes directly (a text
 * editor, a hex viewer, `strings`, an email client's preview pane) sees a
 * plain-language explanation instead of silently-truncated binary noise,
 * and is warned against hand-editing a binary container.
 */
export const DEFAULT_PREAMBLE =
	'\r\n' +
	'This is a .cesvu file. Read it free at https://cesvu.com.\r\n' +
	'Do not edit this file! Modifications will cause data loss.\r\n';

// ── Error type ────────────────────────────────────────────────────────

export type CesvuErrorCode =
	| 'TOO_SHORT'
	| 'BAD_MAGIC'
	| 'UNSUPPORTED_VERSION'
	| 'BAD_PREAMBLE_LENGTH'
	| 'METADATA_CORRUPT'
	| 'METADATA_INCOMPLETE'
	| 'CORRUPTED';

export class CesvuError extends Error {
	constructor(
		public readonly code: CesvuErrorCode,
		message?: string
	) {
		super(message ?? code);
		this.name = 'CesvuError';
	}
}

const PRODUCER_NONCONFORMANT =
	' The file is non-conformant with this build\u2019s plain .cesvu format — the producer (the tool that generated this file) is responsible.';

// ── Envelope metadata (payload prefix) ──────────────────────────────────

/**
 * ⚠️ UNIT: Zod's `.max(n)` on a string counts **UTF-16 code units** (it is
 * `String.prototype.length`), NOT code points.
 */
export const CesvuMetadataSchema = z.object({
	filename: z.string().max(255),
	mimeType: z.string().max(127).default('text/plain'),
	createdAt: z.number().int().nonnegative(),
	template: z.string().max(63).optional()
});

export type CesvuMetadata = z.infer<typeof CesvuMetadataSchema>;

// ── Metadata pack/unpack ─────────────────────────────────────────────────

export function packMetadata(meta: CesvuMetadata): Uint8Array {
	const validated = CesvuMetadataSchema.parse(meta);
	return _encoder.encode(JSON.stringify(validated));
}

export function unpackMetadata(bytes: Uint8Array): CesvuMetadata {
	let json: unknown;
	try {
		json = JSON.parse(_decoder.decode(bytes));
	} catch {
		throw new CesvuError(
			'METADATA_CORRUPT',
			`This .cesvu file's metadata section is not valid JSON.${PRODUCER_NONCONFORMANT}`
		);
	}
	const result = CesvuMetadataSchema.safeParse(json);
	if (!result.success) {
		throw new CesvuError(
			'METADATA_CORRUPT',
			`This .cesvu file's metadata JSON doesn't match the expected schema.${PRODUCER_NONCONFORMANT}`
		);
	}
	return result.data;
}

// ── Checksum helper ───────────────────────────────────────────────────

/** SHA-256 digest of `bytes`, via Web Crypto. */
async function sha256(bytes: Uint8Array): Promise<Uint8Array> {
	// crypto.subtle.digest wants a BufferSource; slice to a fresh buffer
	// defensively when `bytes` is a subarray view over a larger backing
	// buffer, so the digest only ever covers the intended range.
	const view =
		bytes.byteOffset === 0 && bytes.byteLength === bytes.buffer.byteLength
			? bytes
			: bytes.slice();
	const digest = await crypto.subtle.digest('SHA-256', view as BufferSource);
	return new Uint8Array(digest);
}

function constantTimeEqual(a: Uint8Array, b: Uint8Array): boolean {
	if (a.length !== b.length) return false;
	let diff = 0;
	for (let i = 0; i < a.length; i++) diff |= a[i] ^ b[i];
	return diff === 0;
}

// ── Build / parse a plain .cesvu file ───────────────────────────────────

/**
 * Build a plain, checksummed `.cesvu` file from an already-framed
 * `payload` (the caller is responsible for CFP1 framing — see
 * contract-store.svelte.ts's `buildExportPayload`) and its `metadata`.
 *
 * `preamble` defaults to {@link DEFAULT_PREAMBLE} — a short, human-readable
 * banner written right after the fixed header so anyone opening the raw
 * bytes in a text editor sees a plain-language explanation instead of
 * binary noise.
 */
export async function buildCesvuFile(
	payload: Uint8Array,
	metadata: CesvuMetadata,
	preamble: string = DEFAULT_PREAMBLE
): Promise<Uint8Array> {
	const preambleBytes = _encoder.encode(preamble);
	if (preambleBytes.byteLength > MAX_PREAMBLE_LEN) {
		throw new CesvuError(
			'BAD_PREAMBLE_LENGTH',
			`Preamble is ${preambleBytes.byteLength} bytes, exceeding the ${MAX_PREAMBLE_LEN}-byte cap.`
		);
	}
	const metaBytes = packMetadata(metadata);
	if (metaBytes.byteLength > MAX_METADATA_JSON_LEN) {
		throw new CesvuError(
			'METADATA_CORRUPT',
			`Metadata JSON is ${metaBytes.byteLength} bytes, exceeding the ${MAX_METADATA_JSON_LEN}-byte cap.`
		);
	}
	const checksum = await sha256(payload);

	const preambleEnd = FIXED_PREFIX + preambleBytes.byteLength;
	const metaStart = preambleEnd + 2; // + metaLen field
	const metaEnd = metaStart + metaBytes.byteLength;
	const checksumEnd = metaEnd + CHECKSUM_LEN;

	const out = new Uint8Array(checksumEnd + payload.byteLength);
	const dv = new DataView(out.buffer);
	out.set(MAGIC, 0);
	dv.setUint16(6, VERSION, false);
	dv.setUint16(8, preambleBytes.byteLength, false);
	out.set(preambleBytes, FIXED_PREFIX);
	dv.setUint16(preambleEnd, metaBytes.byteLength, false);
	out.set(metaBytes, metaStart);
	out.set(checksum, metaEnd);
	out.set(payload, checksumEnd);
	return out;
}

export interface ParsedCesvuFile {
	metadata: CesvuMetadata;
	/** The human-readable preamble banner (see {@link DEFAULT_PREAMBLE}). */
	preamble: string;
	/** The CFP1-framed payload — pass to the parser that consumes a
	 *  document's framed plaintext (see contract-store.svelte.ts's
	 *  `importFromCesvu`). */
	payload: Uint8Array;
}

/**
 * Parse + integrity-check a plain `.cesvu` file built by
 * {@link buildCesvuFile}. Throws {@link CesvuError} on any structural
 * problem or checksum mismatch — the caller (contract-store.svelte.ts's
 * `importFromCesvu`) maps this to a user-facing message.
 */
export async function parseCesvuFile(bytes: Uint8Array): Promise<ParsedCesvuFile> {
	if (bytes.length < FIXED_PREFIX) {
		throw new CesvuError('TOO_SHORT', 'This file is too short to be a .cesvu file.');
	}
	for (let i = 0; i < MAGIC.length; i++) {
		if (bytes[i] !== MAGIC[i]) {
			throw new CesvuError('BAD_MAGIC', 'This is not a .cesvu file.');
		}
	}
	const dv = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
	const version = dv.getUint16(6, false);
	if (version !== VERSION) {
		throw new CesvuError(
			'UNSUPPORTED_VERSION',
			`This file is v${version}. Use another build of Cesvu that supports v${version} files.`
		);
	}
	const preambleLen = dv.getUint16(8, false);
	if (preambleLen > MAX_PREAMBLE_LEN) {
		throw new CesvuError(
			'BAD_PREAMBLE_LENGTH',
			`This .cesvu file's preamble length prefix (${preambleLen}) exceeds the ${MAX_PREAMBLE_LEN}-byte cap.${PRODUCER_NONCONFORMANT}`
		);
	}
	const preambleStart = FIXED_PREFIX;
	const preambleEnd = preambleStart + preambleLen;
	const metaLenFieldEnd = preambleEnd + 2;
	if (bytes.length < metaLenFieldEnd) {
		throw new CesvuError(
			'METADATA_INCOMPLETE',
			`This .cesvu file's header hasn't fully arrived yet.${PRODUCER_NONCONFORMANT}`
		);
	}
	const preamble = _decoder.decode(bytes.subarray(preambleStart, preambleEnd));

	const metaLen = dv.getUint16(preambleEnd, false);
	if (metaLen === 0 || metaLen > MAX_METADATA_JSON_LEN) {
		throw new CesvuError(
			'METADATA_CORRUPT',
			`This .cesvu file's metadata length prefix (${metaLen}) is out of range.${PRODUCER_NONCONFORMANT}`
		);
	}
	const metaStart = metaLenFieldEnd;
	const metaEnd = metaStart + metaLen;
	const checksumStart = metaEnd;
	const checksumEnd = checksumStart + CHECKSUM_LEN;
	if (bytes.length < checksumEnd) {
		throw new CesvuError(
			'METADATA_INCOMPLETE',
			`This .cesvu file's header hasn't fully arrived yet.${PRODUCER_NONCONFORMANT}`
		);
	}
	const metadata = unpackMetadata(bytes.subarray(metaStart, metaEnd));
	const expectedChecksum = bytes.subarray(checksumStart, checksumEnd);
	const payload = bytes.subarray(checksumEnd);

	const actualChecksum = await sha256(payload);
	if (!constantTimeEqual(actualChecksum, expectedChecksum)) {
		throw new CesvuError(
			'CORRUPTED',
			'This file appears to be corrupted \u2014 its contents don\u2019t match the stored checksum.'
		);
	}

	return { metadata, preamble, payload };
}
