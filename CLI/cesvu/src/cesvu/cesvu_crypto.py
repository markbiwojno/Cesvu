# Profile 3 only, measured in UTF-8 BYTES - not characters. Python's len()
# counts code points and JavaScript's String.length counts UTF-16 code units;
# the two disagree for astral characters, so neither is a portable measure,
# and the old len(passphrase) check made the two tools reject different
# passwords.
#
# WHY 512 AND NOT MORE - this bound must not be raised in isolation. The web
# app's decrypt entry points gate their passphrase input at 512 UTF-16 code
# units, and for every possible string UTF-16 units <= UTF-8 bytes (1:1
# ASCII, 1:2 Cyrillic, 1:3 CJK, 2:4 astral). A byte cap of 512 therefore can
# never admit a passphrase the browser's 512-character input would refuse.
# Raise it above the UI's character cap and this CLI becomes able to create
# files whose passphrase physically cannot be typed into the web app -
# permanently unopenable there. Invariant: this <= the UI's character cap.
