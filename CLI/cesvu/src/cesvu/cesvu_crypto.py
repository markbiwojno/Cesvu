def _secretstream_pull(state, cipher: bytes, ad: Optional[bytes]):
    """Wrapper: PyNaCl raises nacl.exceptions.CryptoError on a failed pull
    (unlike libsodium.js which returns false). Normalize to `None` so
    callers can use the same `if not result:` pattern as the TS side.
    """
    try:
        return sb.crypto_secretstream_xchacha20poly1305_pull(state, cipher, ad)
    except nacl.exceptions.CryptoError:
        return None


def _init_pull(stream_header: bytes, key: bytes):
    """Create a secretstream state and init it for pulling.

    Converts PyNaCl's malformed-input exceptions into
    CesvuError('STREAM_HEADER_INVALID') at the FORMAT BOUNDARY, so a bad
    streamHeader in an untrusted file surfaces as a cesvu error rather
    than a raw ValueError/CryptoError escaping the module.

    See _MALFORMED_INPUT_EXCEPTIONS: backend/environmental failures are
    deliberately NOT caught here, and must not be reported as either a
    format problem or a passphrase problem.
    """
    try:
        state = sb.crypto_secretstream_xchacha20poly1305_state()
        sb.crypto_secretstream_xchacha20poly1305_init_pull(state, stream_header, key)
        return state
    except _MALFORMED_INPUT_EXCEPTIONS as err:
        raise CesvuError(
            "STREAM_HEADER_INVALID",
            "This file's secretstream header could not be used to start decryption — it is "
            "malformed or corrupted." + PRODUCER_NONCONFORMANT,
        ) from err


def _assert_tag_allowed(tag: int) -> None:
    """Item #9 - strict secretstream tag policy. Mirrors assertTagAllowed()
    in cesvu-crypto.ts; both readers MUST enforce this or it becomes new
    drift.

    v1 uses exactly two tags: TAG_MESSAGE (0x00) for every chunk but the
    last, TAG_FINAL (0x03) for the last. libsodium also defines TAG_PUSH
    (0x01) and TAG_REKEY (0x02), and its `pull` accepts them happily - so
    without this check a file carrying them would decrypt, and a TAG_REKEY
    would silently advance the stream key, putting a reader that honours it
    and one that doesn't into permanently different states.

    NOT a breaking change: the tag byte is covered by each chunk's Poly1305
    MAC, and neither this writer nor the TypeScript writer has ever emitted
    anything but 0x00/0x03, so no conformant file can trip it. Because the
    tag is authenticated, reaching this check at all means the passphrase
    was already proven correct - hence CIPHERTEXT_CORRUPT rather than
    anything passphrase-related.
    """
    if tag != _TAG_MESSAGE and tag != _TAG_FINAL:
        raise CesvuError(
            "CIPHERTEXT_CORRUPT",
            f"This file uses an unsupported secretstream chunk tag (0x{tag:02x}). The "
            f".cesvu v1 spec permits only TAG_MESSAGE (0x00) and TAG_FINAL (0x03). The "
            f"chunk authenticated, so the passphrase is CORRECT — the file is "
            f"non-conformant or has been altered." + PRODUCER_NONCONFORMANT,
        )


