# Exceptions that mean "this input is malformed / does not authenticate",
# as opposed to "the crypto backend is broken". PyNaCl raises CryptoError
# for a failed MAC or a bad state, and ValueError/TypeError for
# wrong-length inputs (e.g. a truncated streamHeader).
#
# SECURITY: never widen this to `Exception`. Everything NOT in this tuple —
# a broken libsodium build, MemoryError, an ImportError — must propagate
# unchanged. Classifying an environmental failure as a format/passphrase
# error is the exact inversion the post-auth error codes exist to prevent:
# it would tell a user their passphrase is wrong when it is fine.
_MALFORMED_INPUT_EXCEPTIONS = (nacl.exceptions.CryptoError, ValueError, TypeError)

