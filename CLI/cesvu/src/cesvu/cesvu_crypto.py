def random_bytes(n: int) -> bytes:
    if n is None:
        raise ValueError("random_bytes: n is None — caller must pass an explicit byte count.")
    if n == 0:
        return b""
    if n > 65536:
        raise ValueError(f"random_bytes: n={n} exceeds 65536-byte single-call cap")
    import os

    return os.urandom(n)


# ── Metadata (length-prefixed JSON, inside the ciphertext) ────────────


@dataclass
class CesvuMetadata:
    filename: str
    mimeType: str = "text/plain"
    createdAt: int = 0
    template: Optional[str] = None

    def to_dict(self) -> dict:
        d = {
            "filename": self.filename,
            "mimeType": self.mimeType,
            "createdAt": self.createdAt,
        }
        if self.template is not None:
            d["template"] = self.template
        return d


def _utf16_len(s: str) -> int:
    """Length of `s` in UTF-16 code units — i.e. what JavaScript's
    `String.prototype.length` reports, and therefore what Zod's `.max(n)`
    counts on the TypeScript side.

    Python's `len()` counts CODE POINTS instead. The two agree for the BMP
    but differ for astral characters (emoji, rare CJK), which are a single
    code point in Python and a surrogate PAIR in JavaScript.
    """
    return sum(2 if ord(ch) > 0xFFFF else 1 for ch in s)


def _check_metadata_field(value: str, limit: int, field_name: str) -> None:
    """Enforce `limit` under BOTH length measures on the WRITE path.

    The limits are shared with the TypeScript implementation, whose Zod
    schema counts UTF-16 code units while Python counts code points. Since
    code points <= UTF-16 units for every string, checking only Python's
    measure is the weaker test: a value can satisfy Python and still be
    rejected by TypeScript. That rejection happens AFTER the payload has
    authenticated, so it surfaces as METADATA_CORRUPT_POST_AUTH — the web
    app tells the user their passphrase is correct but refuses to recover
    the file. Requiring both measures here means this implementation can
    only ever emit metadata the other one will accept.

    WRITE PATH ONLY — deliberately not applied in unpack_metadata(). The
    reader still checks code points alone, because tightening a reader can
    only turn files that open today into files that don't. Narrower writer,
    unchanged reader.
    """
    if len(value) > limit:
        raise ValueError(f"CesvuMetadata.{field_name} exceeds {limit} chars")
    if _utf16_len(value) > limit:
        raise ValueError(
            f"CesvuMetadata.{field_name} is {_utf16_len(value)} UTF-16 code units, exceeding the "
            f"{limit} limit (it is only {len(value)} code points — astral characters such as "
            f"emoji count as 2 units each in JavaScript, so this value would be rejected by "
            f"the web app after decryption)"
        )


def pack_metadata(meta: CesvuMetadata) -> bytes:
    _check_metadata_field(meta.filename, 255, "filename")
    _check_metadata_field(meta.mimeType, 127, "mimeType")
    if meta.template is not None:
        _check_metadata_field(meta.template, 63, "template")
    payload = json.dumps(meta.to_dict()).encode("utf-8")
    if len(payload) > MAX_METADATA_JSON_LEN:
        raise ValueError("metadata JSON exceeds MAX_METADATA_JSON_LEN")
    return struct.pack(">H", len(payload)) + payload


@dataclass
class UnpackedMetadata:
    meta: CesvuMetadata
    byte_len: int


def _reject_json_constant(name: str):
    """`json.loads(parse_constant=...)` hook.

    Python's json module accepts the non-standard tokens NaN, Infinity and
    -Infinity by default; JSON.parse does not, and the TS schema's
    z.number().int() would reject them anyway. Rejecting here keeps the two
    implementations agreeing on which byte sequences are valid metadata.
    """
    raise ValueError(f"non-standard JSON constant {name!r} is not permitted in cesvu metadata")


def _metadata_corrupt(detail: str) -> CesvuError:
    return CesvuError(
        "METADATA_CORRUPT",
        f"This .cesvu file's metadata JSON doesn't match the cesvu v1 schema ({detail})."
        + PRODUCER_NONCONFORMANT,
    )


def unpack_metadata(buf: bytes) -> UnpackedMetadata:
    """Parse and VALIDATE the length-prefixed metadata JSON.

    The reference contract is the Zod schema in cesvu-crypto.ts:

        filename:  z.string().max(255)
        mimeType:  z.string().max(127).default('text/plain')
        createdAt: z.number().int().nonnegative()
        template:  z.string().max(63).optional()

    Mirrored here as REJECTION, never coercion. `str(obj["filename"])` would
    happily turn `{"filename": 42}` — which Zod rejects — into the string
    "42", so the two tools would disagree about whether a file is valid.

    Three Python-specific traps this guards against:
      - `isinstance(True, int)` is True, so bool must be excluded explicitly
        or `{"createdAt": true}` silently passes as 1.
      - NaN/Infinity are accepted by json.loads (see _reject_json_constant)
        but rejected by JSON.parse and by z.number().int().
      - Zod's `.default()`/`.optional()` fire on an ABSENT/undefined key
        only; an explicit JSON `null` is a validation FAILURE, not a
        default. So key presence is tested with `in`, never `.get()`.

    UNKNOWN KEYS: Zod's z.object() defaults to "strip" mode — extra keys are
    silently dropped, NOT an error. We match that by ignoring them. Do not
    "harden" this into a rejection without changing the TS side too.

    LENGTH LIMITS: code points here, DELIBERATELY asymmetric with
    pack_metadata(), which additionally requires the UTF-16 measure.

    Zod's .max(n) counts UTF-16 code units; Python's len() counts code
    points. Code points <= UTF-16 units for every string, so this reader is
    the MORE PERMISSIVE of the two: it accepts astral-heavy values (e.g. a
    200-emoji filename: 200 code points, 400 UTF-16 units) that the
    TypeScript reader rejects.

    That asymmetry is kept on purpose. Tightening this check to match Zod
    would newly reject files that open today — turning a cross-language
    interop wrinkle into local data loss. The fix belongs on the WRITE side,
    where refusing to emit such a value costs nothing: see
    _check_metadata_field(). Narrower writer, unchanged reader.
    """
    if len(buf) < 2:
        raise CesvuError(
            "METADATA_INCOMPLETE",
            f"This .cesvu file's decrypted payload is too short to contain metadata yet "
            f"(got {len(buf)} bytes, need at least 2).",
        )
    (length,) = struct.unpack_from(">H", buf, 0)
    if length == 0 or length > MAX_METADATA_JSON_LEN:
        raise CesvuError(
            "METADATA_CORRUPT",
            f"This .cesvu file's metadata length prefix ({length}) is out of range "
            f"(must be 1..{MAX_METADATA_JSON_LEN})." + PRODUCER_NONCONFORMANT,
        )
    if length > len(buf) - 2:
        raise CesvuError(
            "METADATA_INCOMPLETE",
            f"This .cesvu file's metadata ({length} bytes) hasn't fully arrived yet "
            f"(have {len(buf) - 2} bytes so far).",
        )
    json_bytes = buf[2 : 2 + length]
    try:
        obj = json.loads(json_bytes.decode("utf-8"), parse_constant=_reject_json_constant)
    except Exception:
        # Covers invalid UTF-8, malformed JSON, and the NaN/Infinity tokens
        # rejected by _reject_json_constant above. Deliberately broad: every
        # one of these is the same answer to the caller — the metadata
        # section is not parseable — and none may escape as a raw
        # UnicodeDecodeError/ValueError.
        raise CesvuError(
            "METADATA_CORRUPT",
            "This .cesvu file's metadata section is not valid JSON." + PRODUCER_NONCONFORMANT,
        )

    if not isinstance(obj, dict):
        raise _metadata_corrupt("top level is not an object")

    # filename: z.string().max(255) — required.
    if "filename" not in obj:
        raise _metadata_corrupt("missing required field 'filename'")
    filename = obj["filename"]
    if not isinstance(filename, str):
        raise _metadata_corrupt("'filename' is not a string")
    if len(filename) > 255:
        raise _metadata_corrupt(f"'filename' is {len(filename)} chars, exceeding the 255 limit")

    # mimeType: z.string().max(127).default('text/plain'). The default
    # applies to an ABSENT key only; an explicit null is a failure.
    if "mimeType" in obj:
        mime_type = obj["mimeType"]
        if not isinstance(mime_type, str):
            raise _metadata_corrupt("'mimeType' is present but not a string")
        if len(mime_type) > 127:
            raise _metadata_corrupt(
                f"'mimeType' is {len(mime_type)} chars, exceeding the 127 limit"
            )
    else:
        mime_type = "text/plain"

    # createdAt: z.number().int().nonnegative(). bool is excluded FIRST
    # because isinstance(True, int) is True in Python — without this,
    # {"createdAt": true} would be accepted as 1.
    if "createdAt" not in obj:
        raise _metadata_corrupt("missing required field 'createdAt'")
    created_at = obj["createdAt"]
    if isinstance(created_at, bool) or not isinstance(created_at, int):
        raise _metadata_corrupt("'createdAt' is not an integer")
    if created_at < 0:
        raise _metadata_corrupt(f"'createdAt' is negative ({created_at})")

    # template: z.string().max(63).optional() — absent is fine, null is not.
    if "template" in obj:
        template = obj["template"]
        if not isinstance(template, str):
            raise _metadata_corrupt("'template' is present but not a string")
        if len(template) > 63:
            raise _metadata_corrupt(f"'template' is {len(template)} chars, exceeding the 63 limit")
    else:
        template = None

    meta = CesvuMetadata(
        filename=filename,
        mimeType=mime_type,
        createdAt=created_at,
        template=template,
    )
    return UnpackedMetadata(meta=meta, byte_len=2 + length)


# ── Passphrase normalization (must match cesvu-crypto.ts exactly) ────


# NOTHING IN THIS SECTION MAY USE `\s`, `.strip()`, `.lower()`, OR
# `normalize("NFKC")`. Normalization is KEY-DETERMINING: if this module and
# src/lib/crypto/cesvu-crypto.ts disagree by even one code point, the same
# typed passphrase derives two different Argon2id keys and the file fails to
# open with no useful diagnostic.
#
# Every one of those built-ins is defined differently per language AND per
# Unicode version. Measured, Python 3.13 (Unicode 15) vs Node 24 (Unicode 16):
#
#   U+001C-U+001F, U+0085 : Python's \s matches, JavaScript's does NOT
#   U+FEFF                : JavaScript's \s matches, Python's does NOT
#   NFKC                  : differs on 37 code points
#   case mapping          : differs on 55 code points
#   NFC                   : differs on 0   <- why NFC is the one we keep
#
# Only the explicit tables below are portable. See .cesvu SPEC/README.md
# section "passProfile normalization (must match exactly)", and the shared
# vectors in shared/passphrase-vectors.json which both test suites run.

# The 30 code points this format treats as whitespace: the UNION of the
# Python and JavaScript whitespace sets, so neither implementation depends on
# its own runtime's notion of whitespace. Exactly these, no others. Adding
# one silently changes derived keys for every passphrase containing it, so
# this set may only change alongside the format spec and the shared vectors.
CANONICAL_WHITESPACE = frozenset(
    {
        0x0009, 0x000A, 0x000B, 0x000C, 0x000D, 0x001C, 0x001D, 0x001E, 0x001F,
        0x0020, 0x0085, 0x00A0, 0x1680, 0x2000, 0x2001, 0x2002, 0x2003, 0x2004,
        0x2005, 0x2006, 0x2007, 0x2008, 0x2009, 0x200A, 0x2028, 0x2029, 0x202F,
        0x205F, 0x3000, 0xFEFF,
    }
)
assert len(CANONICAL_WHITESPACE) == 30


def normalize_diceware_passphrase(passphrase: str) -> str:
    """Profile 1 - also the DEFAULT profile, so it must be well defined for
    arbitrary input, not merely for wordlist input.

      1. every CANONICAL_WHITESPACE code point -> U+0020
      2. collapse runs of U+0020; drop leading/trailing U+0020
      3. NFC (never NFKC)
      4. lowercase ASCII A-Z ONLY; no other code point is altered

    Idempotent; safe to call on already-normalized input.
    """
    # 1 + 2, driven by the explicit table rather than str.split()/.strip(),
    # both of which use Python's own whitespace definition.
    words = []
    current = []
    for ch in passphrase:
        if ord(ch) in CANONICAL_WHITESPACE:
            if current:
                words.append("".join(current))
                current = []
        else:
            current.append(ch)
    if current:
        words.append("".join(current))

    # 3: NFC, not NFKC.
    s = unicodedata.normalize("NFC", " ".join(words))

    # 4: ASCII-only lowercase. Deliberately NOT str.lower(), which is
    # Unicode-wide and version-skewed.
    return "".join(chr(ord(c) + 32) if "A" <= c <= "Z" else c for c in s)


# Deleted outright by profile 2, in addition to CANONICAL_WHITESPACE.
_EMOJI_DELETE = frozenset(
    {
        0xFE0E, 0xFE0F,                          # variation selectors
        0x200B, 0x200C, 0x200D,                  # ZWSP / ZWNJ / ZWJ
        0xFEFF,                                  # BOM
        0x202A, 0x202B, 0x202C, 0x202D, 0x202E,  # bidi embedding/override
        0x2066, 0x2067, 0x2068, 0x2069,          # bidi isolates
    }
)


def normalize_emoji_passphrase(passphrase: str) -> str:
    """Profile 2: NFC, then delete _EMOJI_DELETE and CANONICAL_WHITESPACE."""
    s = unicodedata.normalize("NFC", passphrase)
    return "".join(
        ch
        for ch in s
        if ord(ch) not in _EMOJI_DELETE and ord(ch) not in CANONICAL_WHITESPACE
    )


def normalize_raw_passphrase(passphrase: str) -> str:
    """Profile 3: IDENTITY. No normalization, trimming, lowercasing, or
    whitespace collapsing. Every code point, including U+0020, is significant.

    NFC was applied here previously and was REMOVED deliberately. Profile 3
    accepts arbitrary input, so it applies zero transformation.

    CONSEQUENCE, BY DESIGN: a password containing accented or composed
    characters is device-dependent. "cafe" with a combining acute (macOS,
    NFD) and the precomposed form (Windows, NFC) render identically in every
    font but are DIFFERENT passwords deriving different keys, with no
    diagnostic available to the user. The spec says user-facing
    custom-password entry points SHOULD warn about this; that belongs in the
    UI, not here.
    """
    return passphrase


def normalize_for_profile(passphrase: str, profile: int) -> str:
    if profile == PASS_PROFILE_EMOJI:
        return normalize_emoji_passphrase(passphrase)
    if profile == PASS_PROFILE_RAW:
        return normalize_raw_passphrase(passphrase)
    return normalize_diceware_passphrase(passphrase)


def prepare_passphrase(passphrase: str, profile: int) -> bytes:
    """THE passphrase gate. Every entry point about to derive a key MUST go
    through this and hand the result to derive_key_from_passphrase() - which
    takes `bytes`, not `str`, precisely so no call site can skip these checks.

    In the order the format spec mandates:
      1. reject lone surrogates (BEFORE encoding - see below)
      2. normalize per profile
      3. encode UTF-8
      4. reject empty
      5. reject over RAW_PASSPHRASE_MAX_BYTES - profile 3 ONLY

    WHY STEP 1 IS WRITTEN OUT RATHER THAN LEFT TO THE ENCODER. Python's
    str.encode("utf-8") does raise UnicodeEncodeError on a lone surrogate, so
    this check is redundant *here* - but it is NOT redundant in the
    TypeScript port, where WHATWG *requires* TextEncoder to substitute U+FFFD
    and never throw:

        Python  s.encode('utf-8')           raises UnicodeEncodeError
        JS      new TextEncoder().encode()  returns 6162 EFBFBD 6364

    Left implicit, JS would silently derive a key from bytes the user never
    typed while Python refused outright - the same typed passphrase, two
    different outcomes. It is spelled out in both languages so the two agree
    by construction, and so this module states the rule rather than
    inheriting it from a CPython implementation detail. Iterating characters
    (code points) means a well-formed astral character is accepted; only LONE
    surrogates are rejected.
    """
    for ch in passphrase:
        if 0xD800 <= ord(ch) <= 0xDFFF:
            raise CesvuError(
                "PASSPHRASE_INVALID_ENCODING",
                "This passphrase contains an unpaired surrogate character "
                "(U+D800-U+DFFF), which cannot be encoded as UTF-8. This "
                "usually means the text was corrupted in transit - for "
                "example emoji pasted through a console or editor that split "
                "a character in half. Retype or re-paste it.",
            )

    encoded = normalize_for_profile(passphrase, profile).encode("utf-8")

    if len(encoded) == 0:
        raise ValueError("prepare_passphrase: passphrase is empty after normalization")

    if profile == PASS_PROFILE_RAW and len(encoded) > RAW_PASSPHRASE_MAX_BYTES:
        raise CesvuError(
            "PASSPHRASE_TOO_LONG",
            f"This password is {len(encoded)} bytes when encoded as UTF-8, which "
            f"exceeds the {RAW_PASSPHRASE_MAX_BYTES}-byte limit. Note the limit is "
            "in bytes, not characters: accented, CJK and emoji characters each "
            "take 2-4 bytes, so a password can exceed it well before it reaches "
            "512 visible characters.",
        )

    return encoded


def passphrase_type_to_profile(t: Optional[str]) -> int:
    if t == "emoji":
        return PASS_PROFILE_EMOJI
    if t == "raw":
        return PASS_PROFILE_RAW
    return PASS_PROFILE_TEXT


# ── KDF (libsodium crypto_pwhash / Argon2id13 + domain separation) ────

STREAM_KEY_CONTEXT = b"cesvu.com/v1/stream-key"
KEYCHECK_CONTEXT = b"cesvu/keycheck/v1"


def derive_key_from_passphrase(
    # bytes, NOT str, ON PURPOSE: the only supported way to produce these is
    # prepare_passphrase(), so no call site can reach Argon2id while skipping
    # the surrogate / normalization / length gate.
    passphrase_bytes: bytes,
    salt: bytes,
    memory_kib: int,
    time_cost: int,
    chunk_shift: int,
) -> bytes:
    """Derive a 32-byte stream key via Argon2id13 + domain-separation BLAKE2b.

    Range-checks chunk_shift, memory_kib, time_cost BEFORE running Argon2id
    (fail-closed on untrusted header input) — same order as the TS side.

    `salt` MUST be exactly crypto_pwhash_SALTBYTES bytes — 16 with standard
    libsodium, NOT 32. The header's 32-byte salt SLOT holds a SALTBYTES salt
    followed by reserved bytes (see build_header), so pass the salt, not the
    slot. parse_header() already slices exactly SALTBYTES for you.
    """
    if len(salt) != _PWHASH_SALTBYTES:
        raise TypeError(f"derive_key_from_passphrase: salt must be {_PWHASH_SALTBYTES} bytes, got {len(salt)}")

    if chunk_shift < CHUNK_SHIFT_MIN or chunk_shift > CHUNK_SHIFT_MAX:
        raise CesvuError(
            "CHUNK_SIZE_OUT_OF_RANGE",
            f"The chunk size encoded as chunkShift={chunk_shift} is outside the cesvu v1 "
            f"spec's allowed range ({CHUNK_SHIFT_MIN}..{CHUNK_SHIFT_MAX})." + PRODUCER_NONCONFORMANT,
        )

    if not isinstance(memory_kib, int) or memory_kib < KDF_MEMORY_KIB_MIN or memory_kib > KDF_MEMORY_KIB_MAX:
        raise CesvuError(
            "KDF_PARAMS_OUT_OF_RANGE",
            f"This file's KDF memory parameter ({memory_kib} KiB) is outside the allowed range "
            f"({KDF_MEMORY_KIB_MIN}..{KDF_MEMORY_KIB_MAX} KiB)." + PRODUCER_NONCONFORMANT,
        )

    if not isinstance(time_cost, int) or time_cost < KDF_TIME_COST_MIN or time_cost > KDF_TIME_COST_MAX:
        raise CesvuError(
            "KDF_PARAMS_OUT_OF_RANGE",
            f"This file's KDF time cost parameter ({time_cost}) is outside the allowed range "
            f"({KDF_TIME_COST_MIN}..{KDF_TIME_COST_MAX})." + PRODUCER_NONCONFORMANT,
        )

    ops_limit = time_cost
    mem_limit = memory_kib * 1024
    pw_bytes = passphrase_bytes

    raw_key = sb.crypto_pwhash_alg(
        32,
        pw_bytes,

        salt,
        ops_limit,
        mem_limit,
        sb.crypto_pwhash_ALG_ARGON2ID13,
    )
    try:
        stream_key = sb.crypto_generichash_blake2b_salt_personal(
            STREAM_KEY_CONTEXT, digest_size=32, key=raw_key
        )
        return stream_key
    finally:
        _zero(bytearray(raw_key)) if isinstance(raw_key, (bytes, bytearray)) else None


def compute_key_check(key: bytes) -> bytes:
    return sb.crypto_generichash_blake2b_salt_personal(KEYCHECK_CONTEXT, digest_size=32, key=key)


def _constant_time_equal(a: bytes, b: bytes) -> bool:
    if len(a) != len(b):
        return False
    return sb.sodium_memcmp(a, b)


def _zero(buf: bytearray) -> None:
    """Overwrite a MUTABLE bytearray in place. BEST-EFFORT ONLY.

    ⚠️ READ BEFORE TRUSTING THIS. Every call site in this module passes
    `bytearray(key)`, where `key` is the immutable `bytes` object PyNaCl
    returned. `bytearray(...)` COPIES, so what gets wiped is the throwaway
    copy — the original `key` bytes are untouched and remain in the heap
    until the garbage collector reclaims them, and possibly in the swap
    file or a core dump after that.

    This is not a bug that can be fixed here: PyNaCl's crypto_pwhash_alg /
    crypto_generichash_* return `bytes`, and CPython gives no supported way
    to mutate an immutable `bytes` object. Fixing it properly means the KDF
    returning a caller-owned `bytearray` all the way down, which changes
    every signature that touches key material.

    So: treat key erasure in this module as a defence-in-depth gesture that
    reduces the number of copies lying around, NOT as a guarantee that key
    material has been erased from process memory. Do not write comments or
    docs elsewhere that imply otherwise.
    """
    try:
        sb.sodium_memzero(buf)
    except Exception:
        for i in range(len(buf)):
            buf[i] = 0


def matches_unauthenticated_header_key_check(header_bytes: bytes, passphrase: str) -> bool:
    """Check a passphrase against ONLY the header's unauthenticated keyCheck.

    ⚠️ SECURITY — THIS IS NOT PROOF THAT THE PASSPHRASE WILL DECRYPT THE FILE.

    keyCheck lives in the PUBLIC, UNAUTHENTICATED header, and this function
    never touches a byte of ciphertext, so it verifies no secretstream MAC.
    An attacker who can modify the file can rewrite salt, KDF params,
    passProfile, streamHeader and keyCheck together as a consistent set,
    making this return True for a passphrase of the ATTACKER's choosing.

    Use only as a latency optimization for interactive UX. NEVER for an
    authorization or trust decision — use verify_passphrase() for that.

    Mirrors matchesUnauthenticatedHeaderKeyCheck() in cesvu-crypto.ts.
    """
    parsed = parse_header(header_bytes)
    pw_bytes = prepare_passphrase(passphrase, parsed.pass_profile)
    key = derive_key_from_passphrase(
        pw_bytes, parsed.salt, parsed.kdf_memory_kib, parsed.kdf_time_cost, parsed.chunk_shift
    )
    try:
        computed = compute_key_check(key)
        return _constant_time_equal(computed, parsed.key_check)
    finally:
        _zero(bytearray(key))


def verify_passphrase(data: bytes, passphrase: str) -> bool:
    """Verify a passphrase by AUTHENTICATING it against the file's FIRST
    CIPHERTEXT SEGMENT — without decrypting the whole body.

    The keyCheck comparison is a cheap early reject (an OPTIMIZATION only,
    never treated as proof); the authoritative step is the secretstream
    pull over the first segment with the FULL HEADER bound as associated
    data. That MAC covers both the ciphertext and every header field, so a
    header rewritten to match an attacker-chosen password cannot yield True.

    `data` MUST therefore contain the header plus at least the first
    encrypted segment — a header alone can never be authenticated and
    raises TOO_SHORT rather than silently degrading to a keyCheck-only
    answer. Only the first segment is examined, so this stays cheap on
    large files.

    ⚠️ SCOPE: True authenticates the header and ONLY the first framed
    segment selected below — nothing more. It is NOT an integrity check on
    the rest of the body. A file whose LATER chunks are corrupted, or that
    is truncated after segment 1, still returns True here and then fails in
    decrypt_cesvu() / decrypt_cesvu_stream() with CIPHERTEXT_CORRUPT or
    TRUNCATED. That is the intended division of labour: this answers "is the
    passphrase right?", the decrypt answers "is the whole file intact?".

    APPENDED DATA is the subtle case, and depends entirely on framing. The
    "first segment" is a fixed-size slice, cipher_body[:chunk_size+ABYTES].
    If the body is NOT segment-aligned (the common case — the final segment
    is short), appended bytes land INSIDE that slice, the MAC over it fails,
    and this returns False. Only when the body happens to be exactly
    segment-aligned do the appended bytes fall outside the slice, in which
    case this returns True and the append surfaces later as TRAILING_DATA
    during a full decrypt. So: do NOT document or rely on this function
    returning True for appended-data files — it may return either answer,
    determined by the file's segment framing rather than by anything
    semantically meaningful.

    Mirrors verifyPassphrase() in cesvu-crypto.ts.
    """
    parsed = parse_header(data)
    header_bytes = data[: parsed.ciphertext_offset]
    cipher_body = data[parsed.ciphertext_offset :]

    if len(cipher_body) < _SECRETSTREAM_ABYTES:
        raise CesvuError(
            "TOO_SHORT",
            f"verify_passphrase needs the header plus at least the first ciphertext segment "
            f"(got {len(cipher_body)} ciphertext bytes, need at least {_SECRETSTREAM_ABYTES}). "
            f"Pass the whole file. To check only the unauthenticated header keyCheck, call "
            f"matches_unauthenticated_header_key_check() — but read its security warning first.",
        )

    # Gate the caller's passphrase before spending an Argon2id run on it.
    pw_bytes = prepare_passphrase(passphrase, parsed.pass_profile)

    # Only the first segment is needed; a short final segment is fine.
    segment_size = (1 << parsed.chunk_shift) + _SECRETSTREAM_ABYTES
    first_seg = cipher_body[:segment_size]

    key = derive_key_from_passphrase(
        pw_bytes, parsed.salt, parsed.kdf_memory_kib, parsed.kdf_time_cost, parsed.chunk_shift
    )
    try:
        # Cheap early reject on the SAME derived key (no second Argon2id
        # run). A mismatch is conclusive proof of failure; a match proves
        # nothing on its own, so it still falls through to the MAC check.
        computed = compute_key_check(key)
        if not _constant_time_equal(computed, parsed.key_check):
            return False

        try:
            state = _init_pull(parsed.stream_header, key)
            result = _secretstream_pull(state, first_seg, header_bytes)
        except _MALFORMED_INPUT_EXCEPTIONS:
            # A tampered streamHeader can make init_pull raise rather than
            # return None. Either way the passphrase does not authenticate.
            #
            # SECURITY: NARROW on purpose — see _MALFORMED_INPUT_EXCEPTIONS.
            # A broken libsodium build or an OOM must NOT be silently
            # converted into "wrong passphrase"; anything unlisted (and the
            # CesvuError _init_pull may raise) propagates.
            return False
        return bool(result)
    finally:
        _zero(bytearray(key))



# ── Header construction (SINGLE SOURCE OF TRUTH for write offsets) ───


def build_header(
    preamble: str,
    salt: bytes,
    memory_kib: int,
    time_cost: int,
    chunk_shift: int,
    pass_profile: int,
    stream_header: bytes,
    key_check: bytes,
    cipher_mode: int = CIPHER_MODE_SECRETSTREAM_XCHACHA20POLY1305,
) -> bytes:
    if len(stream_header) != _SECRETSTREAM_HEADERBYTES:
        raise CesvuError(
            "STREAM_HEADER_INVALID",
            f"build_header: streamHeader must be {_SECRETSTREAM_HEADERBYTES} bytes, got {len(stream_header)}",
        )
    if len(key_check) != KEYCHECK_LEN:
        raise TypeError(f"build_header: keyCheck must be {KEYCHECK_LEN} bytes, got {len(key_check)}")
    if chunk_shift < CHUNK_SHIFT_MIN or chunk_shift > CHUNK_SHIFT_MAX:
        raise CesvuError(
            "CHUNK_SIZE_OUT_OF_RANGE",
            f"The chunk size encoded as chunkShift={chunk_shift} is outside the cesvu v1 spec's "
            f"allowed range ({CHUNK_SHIFT_MIN}..{CHUNK_SHIFT_MAX})." + PRODUCER_NONCONFORMANT,
        )
    preamble_bytes = preamble.encode("utf-8")
    if len(preamble_bytes) > MAX_PREAMBLE_LEN:
        raise ValueError(f"build_header: preamble length {len(preamble_bytes)} > MAX_PREAMBLE_LEN {MAX_PREAMBLE_LEN}")
    if len(salt) != _PWHASH_SALTBYTES:
        raise TypeError(f"build_header: salt must be {_PWHASH_SALTBYTES} bytes, got {len(salt)}")
    if memory_kib < KDF_MEMORY_KIB_MIN or memory_kib > KDF_MEMORY_KIB_MAX:
        raise CesvuError("KDF_PARAMS_OUT_OF_RANGE", "The KDF parameters are outside the cesvu v1 spec's allowed range." + PRODUCER_NONCONFORMANT)
    if time_cost < KDF_TIME_COST_MIN or time_cost > KDF_TIME_COST_MAX:
        raise CesvuError("KDF_PARAMS_OUT_OF_RANGE", "The KDF parameters are outside the cesvu v1 spec's allowed range." + PRODUCER_NONCONFORMANT)
    if cipher_mode not in _IMPLEMENTED_CIPHER_MODES:
        raise CesvuError(
            "UNSUPPORTED_CIPHER_MODE",
            f"build_header: cipherMode {cipher_mode} is not implemented by this build.",
        )
    if pass_profile not in (PASS_PROFILE_TEXT, PASS_PROFILE_EMOJI, PASS_PROFILE_RAW):
        raise CesvuError(
            "KDF_PARAMS_OUT_OF_RANGE",
            f"build_header: passProfile {pass_profile} is not valid (expected 1=text, 2=emoji, or 3=raw).",
        )

    pl = len(preamble_bytes)
    out = bytearray(FIXED_PREFIX + pl + POST_PREAMBLE_FIXED)
    out[0:6] = MAGIC
    struct.pack_into(">H", out, 6, VERSION)
    struct.pack_into(">H", out, 8, pl)
    out[FIXED_PREFIX : FIXED_PREFIX + pl] = preamble_bytes

    base = FIXED_PREFIX + pl
    out[base] = cipher_mode
    struct.pack_into(">I", out, base + 1, memory_kib)
    out[base + 5] = time_cost
    out[base + 6] = pass_profile
    out[base + 7 : base + 7 + _PWHASH_SALTBYTES] = salt
    struct.pack_into(">H", out, base + 39, chunk_shift)
    out[base + 41 : base + 41 + _SECRETSTREAM_HEADERBYTES] = stream_header
    out[base + 73 : base + 73 + KEYCHECK_LEN] = key_check

    return bytes(out)


# ── Header parsing (SINGLE SOURCE OF TRUTH for read offsets) ─────────


@dataclass
class ParsedHeader:
    version: int
    cipher_mode: int
    mode: str
    salt: bytes
    kdf_memory_kib: int
    kdf_time_cost: int
    chunk_shift: int
    pass_profile: int
    stream_header: bytes
    key_check: bytes
    ciphertext_offset: int


def parse_header(data: bytes) -> ParsedHeader:
    # SCOPE: validates the HEADER ONLY, so it requires only enough bytes to
    # contain a header — deliberately NOT any ciphertext. "Is this a
    # well-formed header?" and "is this a complete file?" are separate
    # questions.
    #
    # This previously also added _SECRETSTREAM_ABYTES, demanding room for
    # the first chunk's MAC. That made a VALID maximum-preamble header
    # delivered as one exact standalone chunk fail with TOO_SHORT at
    # precisely the length where a streaming reader stops accumulating
    # header bytes. MUST stay in lockstep with the TypeScript parseHeader()
    # in src/lib/crypto/cesvu-crypto.ts, which made the identical change —
    # otherwise the two implementations disagree on which byte sequences
    # constitute a valid header.
    #
    # Ciphertext-length validation stays where it belongs: decrypt_cesvu()
    # below already enforces the _SECRETSTREAM_ABYTES minimum on the body.
    min_len = FIXED_PREFIX + POST_PREAMBLE_FIXED
    if len(data) < min_len:

        raise CesvuError(
            "TOO_SHORT",
            f"This file is too short to be a valid cesvu file (got {len(data)} bytes, "
            f"need at least {min_len}). It's either truncated or not a cesvu file at all.",
        )
    if data[0:6] != MAGIC:
        raise CesvuError(
            "BAD_MAGIC",
            "This file is not a cesvu file — its header doesn't start with the expected magic bytes."
            + PRODUCER_NONCONFORMANT,
        )
    (version,) = struct.unpack_from(">H", data, 6)
    if version != VERSION:
        raise CesvuError(
            "UNSUPPORTED_VERSION",
            f"This cesvu file uses v{version}, which this app doesn't support (only v{VERSION} "
            f"is supported)." + PRODUCER_NONCONFORMANT,
        )
    (pl,) = struct.unpack_from(">H", data, 8)
    if pl > MAX_PREAMBLE_LEN:
        raise CesvuError(
            "BAD_PREAMBLE_LENGTH",
            f"The preamble length ({pl} bytes) in this file's header exceeds the cesvu v1 spec "
            f"max of {MAX_PREAMBLE_LEN} bytes." + PRODUCER_NONCONFORMANT,
        )
    if FIXED_PREFIX + pl + POST_PREAMBLE_FIXED > len(data):
        raise CesvuError(
            "TOO_SHORT",
            "This file's header declares more bytes than the file actually contains — it's "
            "truncated or corrupted." + PRODUCER_NONCONFORMANT,
        )
    # The preamble field is skipped as OPAQUE padding — never decoded or
    # validated. This package no longer reads/displays/customizes preamble
    # text (see DEFAULT_PREAMBLE); only its declared LENGTH matters, so the
    # offset math below can correctly locate the rest of the header.
    base = FIXED_PREFIX + pl
    cipher_mode = data[base]
    mode_name = CIPHER_MODE_NAMES.get(cipher_mode)
    if mode_name is None or cipher_mode not in _IMPLEMENTED_CIPHER_MODES:
        raise CesvuError(
            "UNSUPPORTED_CIPHER_MODE",
            f"This cesvu file declares cipherMode {cipher_mode}"
            + (f" ({mode_name})" if mode_name else "")
            + ", which this app doesn't support."
            + PRODUCER_NONCONFORMANT,
        )
    (memory_kib,) = struct.unpack_from(">I", data, base + 1)
    time_cost = data[base + 5]
    pass_profile = data[base + 6]
    salt = data[base + 7 : base + 7 + _PWHASH_SALTBYTES]
    (chunk_shift,) = struct.unpack_from(">H", data, base + 39)
    stream_header = data[base + 41 : base + 41 + _SECRETSTREAM_HEADERBYTES]
    key_check = data[base + 73 : base + 73 + KEYCHECK_LEN]
    ciphertext_offset = base + POST_PREAMBLE_FIXED

    if chunk_shift < CHUNK_SHIFT_MIN or chunk_shift > CHUNK_SHIFT_MAX:
        raise CesvuError(
            "CHUNK_SIZE_OUT_OF_RANGE",
            f"The chunk size encoded as chunkShift={chunk_shift} is outside the cesvu v1 spec's "
            f"allowed range ({CHUNK_SHIFT_MIN}..{CHUNK_SHIFT_MAX})." + PRODUCER_NONCONFORMANT,
        )
    if memory_kib < KDF_MEMORY_KIB_MIN or memory_kib > KDF_MEMORY_KIB_MAX:
        raise CesvuError(
            "KDF_PARAMS_OUT_OF_RANGE",
            f"The KDF parameters in this file are outside the cesvu v1 spec's allowed range "
            f"(memory must be {KDF_MEMORY_KIB_MIN}..{KDF_MEMORY_KIB_MAX} KiB)." + PRODUCER_NONCONFORMANT,
        )
    if time_cost < KDF_TIME_COST_MIN or time_cost > KDF_TIME_COST_MAX:
        raise CesvuError(
            "KDF_PARAMS_OUT_OF_RANGE",
            f"The KDF parameters in this file are outside the cesvu v1 spec's allowed range "
            f"(time cost must be {KDF_TIME_COST_MIN}..{KDF_TIME_COST_MAX})." + PRODUCER_NONCONFORMANT,
        )
    if pass_profile not in (PASS_PROFILE_TEXT, PASS_PROFILE_EMOJI, PASS_PROFILE_RAW):
        raise CesvuError(
            "KDF_PARAMS_OUT_OF_RANGE",
            f"This file declares passProfile {pass_profile}, which this app doesn't recognize."
            + PRODUCER_NONCONFORMANT,
        )

    return ParsedHeader(
        version=version,
        cipher_mode=cipher_mode,
        mode=mode_name,
        salt=bytes(salt),
        kdf_memory_kib=memory_kib,
        kdf_time_cost=time_cost,
        chunk_shift=chunk_shift,
        pass_profile=pass_profile,
        stream_header=bytes(stream_header),
        key_check=bytes(key_check),
        ciphertext_offset=ciphertext_offset,
    )


# ── Streaming encrypt ──────────────────────────────────────────────────


def encrypt_cesvu_stream(
    plaintext_chunks: Iterable[bytes],
    passphrase: str,
    metadata: CesvuMetadata,
    passphrase_type: Optional[str] = None,
    memory_kib: int = KDF_MEMORY_KIB_DEFAULT,
    time_cost: int = KDF_TIME_COST_DEFAULT,
    chunk_shift: int = CHUNK_SHIFT_DEFAULT,
) -> Iterator[bytes]:
    """Streaming encrypt: yields `header`, then ciphertext chunks.

    Mirrors encryptCesvuStream in cesvu-crypto.ts.

    MEMORY: peak usage is O(chunk_size) — where chunk_size is
    `1 << chunk_shift`, so at most 16 MiB — ONLY IF the caller's individual
    pieces are themselves bounded. This is a contract on the CALLER, not a
    property this function can guarantee.

    The reason is `buf += piece` in chunk_source() below: it accumulates
    until it has a full chunk, but it cannot accumulate LESS than one whole
    piece. Yield a 4 GiB bytes object from `plaintext_chunks` and peak
    memory is 4 GiB, whatever chunk_shift says. The bound is therefore
    O(chunk_size + max(len(piece))).

    Callers streaming from a file should read in bounded blocks (a
    chunk_size-sized read is the natural choice). This is documented rather
    than enforced: rejecting or re-splitting oversized pieces would change
    behaviour for existing callers, and the caller already knows its own
    read size.
    """
    pass_profile = passphrase_type_to_profile(passphrase_type)
    # Gate + normalize + encode once, before any key derivation.
    pw_bytes = prepare_passphrase(passphrase, pass_profile)

    meta_prefix = pack_metadata(metadata)
    chunk_size = 1 << chunk_shift
    salt = random_bytes(_PWHASH_SALTBYTES)

    key = derive_key_from_passphrase(pw_bytes, salt, memory_kib, time_cost, chunk_shift)

    try:
        state = sb.crypto_secretstream_xchacha20poly1305_state()
        stream_header = sb.crypto_secretstream_xchacha20poly1305_init_push(state, key)
        key_check = compute_key_check(key)


        header = build_header(
            preamble=DEFAULT_PREAMBLE,
            salt=salt,
            memory_kib=memory_kib,
            time_cost=time_cost,
            chunk_shift=chunk_shift,
            pass_profile=pass_profile,
            stream_header=stream_header,
            key_check=key_check,
        )
        yield header

        # Chunk assembler: meta_prefix first, then plaintext_chunks, packed
        # into fixed chunk_size buffers (except possibly the last).
        def chunk_source() -> Iterator[bytes]:
            buf = bytearray()
            buf += meta_prefix
            it = iter(plaintext_chunks)
            while True:
                while len(buf) < chunk_size:
                    try:
                        piece = next(it)
                    except StopIteration:
                        piece = None
                    if piece is None:
                        break
                    if len(piece) == 0:
                        continue
                    buf += piece
                if len(buf) == 0:
                    return
                if len(buf) >= chunk_size:
                    yield bytes(buf[:chunk_size])
                    buf = buf[chunk_size:]
                else:
                    yield bytes(buf)
                    return

        src = chunk_source()
        first_chunk_emitted = False
        try:
            chunk = next(src)
        except StopIteration:
            chunk = None

        while chunk is not None:
            try:
                nxt = next(src)
            except StopIteration:
                nxt = None
            is_last = nxt is None
            tag = _TAG_FINAL if is_last else _TAG_MESSAGE
            ad = None if first_chunk_emitted else header
            ct = sb.crypto_secretstream_xchacha20poly1305_push(state, chunk, ad, tag)
            yield ct
            first_chunk_emitted = True
            chunk = nxt
    finally:
        _zero(bytearray(key))


def encrypt_cesvu(
    plaintext: bytes,
    passphrase: str,
    metadata: CesvuMetadata,
    passphrase_type: Optional[str] = None,
    memory_kib: int = KDF_MEMORY_KIB_DEFAULT,
    time_cost: int = KDF_TIME_COST_DEFAULT,
    chunk_shift: int = CHUNK_SHIFT_DEFAULT,
) -> bytes:
    """One-shot encrypt (buffers the whole ciphertext)."""
    out = bytearray()
    for chunk in encrypt_cesvu_stream(
        [plaintext],
        passphrase,
        metadata,
        passphrase_type=passphrase_type,
        memory_kib=memory_kib,
        time_cost=time_cost,
        chunk_shift=chunk_shift,
    ):
        out += chunk
    return bytes(out)


# ── Streaming decrypt ──────────────────────────────────────────────────


@dataclass
class DecryptedCesvu:
    plaintext: bytes
    metadata: CesvuMetadata
    mode: str
    kdf_memory_kib: int
    kdf_time_cost: int
    pass_profile: int


def _split_cipher_chunks(cipher_body: bytes, chunk_size: int, ab_bytes: int) -> Iterator[bytes]:
    segment_size = chunk_size + ab_bytes
    for off in range(0, len(cipher_body), segment_size):
        yield cipher_body[off : off + segment_size]


def decrypt_cesvu(bytes_in: bytes, passphrase: str) -> DecryptedCesvu:
    """One-shot decrypt (buffers the whole plaintext)."""
    parsed = parse_header(bytes_in)
    header_bytes = bytes_in[: parsed.ciphertext_offset]
    cipher_body = bytes_in[parsed.ciphertext_offset :]

    if len(cipher_body) < _SECRETSTREAM_ABYTES:
        raise CesvuError(
            "TOO_SHORT",
            f"This file's ciphertext ({len(cipher_body)} bytes) is shorter than the minimum "
            f"{_SECRETSTREAM_ABYTES}-byte secretstream MAC — it's truncated or corrupted."
            + PRODUCER_NONCONFORMANT,
        )

    pw_bytes = prepare_passphrase(passphrase, parsed.pass_profile)

    chunk_size = 1 << parsed.chunk_shift

    key = derive_key_from_passphrase(
        pw_bytes, parsed.salt, parsed.kdf_memory_kib, parsed.kdf_time_cost, parsed.chunk_shift
    )
    try:
        computed_key_check = compute_key_check(key)
        if not _constant_time_equal(computed_key_check, parsed.key_check):
            # Pre-authentication: a failed keyCheck and a tampered header are
            # deliberately indistinguishable here.
            raise CesvuError(
                "WRONG_PASSPHRASE_OR_HEADER_TAMPER",
                "Wrong passphrase. Check the words or emoji and try again.",
            )

        # Raises CesvuError('STREAM_HEADER_INVALID') on a malformed
        # streamHeader; backend failures propagate untouched.
        state = _init_pull(parsed.stream_header, key)

        out = bytearray()
        is_first = True
        tag_final_seen = False

        # Has ANY segment's MAC verified yet? Once one has, the passphrase is
        # cryptographically proven correct, so every later failure is file
        # corruption — never a bad password. This flag is what lets the errors
        # below tell the truth instead of blaming the passphrase for damage.
        authenticated = False

        segments = _split_cipher_chunks(cipher_body, chunk_size, _SECRETSTREAM_ABYTES)
        for seg in segments:
            if len(seg) == 0:
                continue
            ad = header_bytes if is_first else None
            result = _secretstream_pull(state, seg, ad)
            if not result:
                # Split by whether anything has authenticated yet. Before the
                # first successful pull this is genuinely ambiguous; after it,
                # blaming the passphrase would be a lie.
                if authenticated:
                    raise CesvuError(
                        "CIPHERTEXT_CORRUPT",
                        "This file is damaged: a chunk failed its authentication check partway "
                        "through. The passphrase is CORRECT (an earlier chunk already verified "
                        "with it), so re-entering it will not help — the file itself has been "
                        "altered or corrupted in transit/storage.",
                    )
                raise CesvuError(
                    "WRONG_PASSPHRASE_OR_HEADER_TAMPER",
                    "Wrong passphrase. Check the words or emoji and try again. (If you're sure "
                    "the passphrase is correct, the file may be corrupted or the producer is "
                    "non-conformant.)",
                )
            message, tag = result
            # This chunk's MAC verified, so the key — and therefore the
            # passphrase — is now proven correct.
            authenticated = True
            is_first = False
            _assert_tag_allowed(tag)
            if len(message) > 0:
                out += message
            if tag == _TAG_FINAL:
                tag_final_seen = True
                break

        if tag_final_seen:
            for trailing in segments:
                if len(trailing) > 0:
                    # Only reachable after TAG_FINAL, so authentication has
                    # definitively succeeded. This is a malformed/appended
                    # file, never a passphrase problem.
                    raise CesvuError(
                        "TRAILING_DATA",
                        f"This file has {len(trailing)} unexpected bytes after its final chunk. "
                        f"Everything up to that point decrypted and authenticated correctly, so "
                        f"the passphrase is CORRECT — but data has been appended to the file."
                        + PRODUCER_NONCONFORMANT,
                    )
        elif authenticated:
            # At least one chunk authenticated, so the key is right and the
            # stream simply stopped early: the file is truncated. Telling the
            # user to re-enter a passphrase that already worked would be false
            # AND would cost them another full Argon2id derivation.
            raise CesvuError(
                "TRUNCATED",
                "This file is incomplete: the encrypted stream ends without its final chunk. "
                "The passphrase is CORRECT (earlier chunks decrypted successfully) — the file "
                "itself was truncated, so re-entering the passphrase will not help. Any data "
                "recovered from it is only a PREFIX of the original and must not be treated as "
                "the whole file.",
            )
        else:
            # Nothing ever authenticated — genuinely ambiguous.
            raise CesvuError(
                "WRONG_PASSPHRASE_OR_HEADER_TAMPER",
                "The encrypted stream ended without a TAG_FINAL chunk — the file is truncated "
                "or corrupted." + PRODUCER_NONCONFORMANT,
            )

        if len(out) < 2:
            raise CesvuError(
                "METADATA_CORRUPT_POST_AUTH",
                f"This file decrypted and authenticated correctly — the passphrase is CORRECT — "
                f"but its payload is only {len(out)} byte(s), too short to contain the required "
                f"metadata prefix." + PRODUCER_NONCONFORMANT,
            )

        try:
            unpacked = unpack_metadata(bytes(out))
        except CesvuError as err:
            if err.code in ("METADATA_CORRUPT", "METADATA_INCOMPLETE"):
                # The stream authenticated end-to-end before we got here, so
                # the passphrase is proven correct and the metadata is
                # genuinely malformed.
                raise CesvuError(
                    "METADATA_CORRUPT_POST_AUTH",
                    "This file decrypted and authenticated correctly — the passphrase is "
                    "CORRECT — but its embedded metadata is malformed, so the original filename "
                    "and type can't be recovered." + PRODUCER_NONCONFORMANT,
                ) from err
            raise


        plaintext = bytes(out[unpacked.byte_len :])
        return DecryptedCesvu(
            plaintext=plaintext,
            metadata=unpacked.meta,
            mode=parsed.mode,
            kdf_memory_kib=parsed.kdf_memory_kib,
            kdf_time_cost=parsed.kdf_time_cost,
            pass_profile=parsed.pass_profile,
        )
    finally:
        _zero(bytearray(key))


def decrypt_cesvu_stream(
    ciphertext_chunks: Iterable[bytes], passphrase: str
) -> Iterator[bytes]:
    """Streaming decrypt generator. Yields plaintext chunks (metadata prefix
    stripped). The final `.metadata`/`.mode` are attached to the
    generator's StopIteration via `.value` is NOT supported in plain Python
    generators the way JS async generators return a value, so callers that
    need metadata should prefer `decrypt_cesvu_stream_full`, which returns
    a (iterator, header_info) pair up front (the header is fully available
    before any plaintext is yielded, unlike the TS version which discovers
    metadata mid-stream).
    """
    inner = decrypt_cesvu_stream_full(ciphertext_chunks, passphrase)[0]
    try:
        for chunk in inner:
            yield chunk
    finally:
        # If the CONSUMER abandons this generator early, our finally runs but
        # `inner` would otherwise be left suspended — holding the secretstream
        # state and the derived key alive, and never running the key-zeroing in
        # its own finally, until GC happens to collect it.
        close = getattr(inner, "close", None)
        if close is not None:
            try:
                close()
            except Exception:
                pass  # best-effort


class DecryptStreamSession(tuple):
    """The (plaintext_iterator, header_info) pair, usable as a context manager.

    Subclasses tuple so the historical `it, info = decrypt_cesvu_stream_full(...)`
    unpacking keeps working unchanged. The addition is __enter__/__exit__:

        with decrypt_cesvu_stream_full(chunks, pw) as (chunks_out, info):
            for piece in chunks_out:
                sink.write(piece)

    On exit the iterator is closed, which runs its `finally` — releasing the
    segment generator and wiping the derived key — even if the body raised
    or broke out early. Without this, abandoning the iterator leaves it
    suspended and its key material reachable until GC.
    """

    __slots__ = ()

    def __new__(cls, iterator, header_info):
        return super().__new__(cls, (iterator, header_info))

    @property
    def iterator(self):
        return self[0]

    @property
    def header_info(self):
        return self[1]

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        self.close()
        return False

    def close(self) -> None:
        close = getattr(self[0], "close", None)
        if close is not None:
            try:
                close()
            except Exception:
                pass  # best-effort


def decrypt_cesvu_stream_full(ciphertext_chunks: Iterable[bytes], passphrase: str):
    """Returns a DecryptStreamSession: (plaintext_chunk_iterator, header_info).

    Unlike the TS streaming decrypt (which must accumulate bytes until the
    header is fully buffered, since it starts from an unknown-length async
    chunk stream), the Python CLI reads a file: header parsing can happen by
    peeking at the front of the buffered file bytes. This helper still
    supports true streaming decrypt (constant memory), it just requires the
    header to be present in the first chunk(s) supplied.

    The result is a tuple subclass, so `it, info = ...` still works, but
    prefer the context-manager form (see DecryptStreamSession) so the key
    is wiped even when the iterator is abandoned.

    WHAT RUNS EAGERLY vs LAZILY — this split is deliberate:

      EAGER (at call time): header buffering + parse_header(), the
      passphrase length/emptiness checks, and the minimum-ciphertext-length
      check. All are cheap, structural, and key-independent, so a caller
      only inspecting a file's header never pays for Argon2id.

      LAZY (on the first next()): derive_key_from_passphrase(),
      compute_key_check(), the keyCheck comparison, and init_pull. These
      all touch key material, so they live INSIDE the generator's
      try/finally — that is the only arrangement where closing an
      un-iterated generator can wipe the key. Deriving eagerly would put
      the key in this function's closure, where `finally` can never reach
      it if the caller never iterates.

    Consequence: WRONG_PASSPHRASE_OR_HEADER_TAMPER surfaces on the first
    next(), not from this call.
    """
    it = iter(ciphertext_chunks)
    buf = bytearray()
    max_header_len = FIXED_PREFIX + MAX_PREAMBLE_LEN + POST_PREAMBLE_FIXED
    parsed: Optional[ParsedHeader] = None
    while parsed is None:
        try:
            parsed = parse_header(bytes(buf))
        except CesvuError as err:
            if err.code != "TOO_SHORT" or len(buf) >= max_header_len:
                raise
            try:
                nxt = next(it)
            except StopIteration:
                raise CesvuError("TOO_SHORT", "Stream produced no chunks.")
            buf += nxt

    # EAGER on purpose (see this function's docstring): cheap, structural and
    # key-independent, so a caller that only inspects the header never pays
    # for Argon2id, and a bad passphrase is reported from this call rather
    # than from the first next().
    pw_bytes = prepare_passphrase(passphrase, parsed.pass_profile)

    header_bytes = bytes(buf[: parsed.ciphertext_offset])
    chunk_size = 1 << parsed.chunk_shift
    segment_size = chunk_size + _SECRETSTREAM_ABYTES

    leftover = bytearray(buf[parsed.ciphertext_offset :])

    def body_segments() -> Iterator[bytes]:
        nonlocal leftover
        while True:
            while len(leftover) >= segment_size:
                yield bytes(leftover[:segment_size])
                leftover = leftover[segment_size:]
            try:
                nxt = next(it)
            except StopIteration:
                if len(leftover) > 0:
                    yield bytes(leftover)
                    leftover = bytearray()
                return
            leftover += nxt

    # Peek the first segment BEFORE deriving the key. A well-formed header
    # with no ciphertext at all is a structural problem, not a passphrase
    # one — calling it "wrong passphrase" would send the user to retry a
    # derivation that was never even attempted, and running Argon2id first
    # would burn seconds of CPU to answer a question the file's length
    # already settled.
    segs = body_segments()
    try:
        first_seg = next(segs)
    except StopIteration:
        segs.close()
        raise CesvuError(
            "TOO_SHORT",
            "This file has a valid header but no ciphertext at all — it is truncated."
            + PRODUCER_NONCONFORMANT,
        )

    # A body too short to hold even one secretstream MAC cannot authenticate,
    # no matter what the passphrase is. Reject it HERE, before Argon2id: a
    # 1..16-byte body would otherwise burn a full derivation (up to 256 MiB
    # at time-cost 10) only to surface as pre-auth passphrase ambiguity,
    # blaming the user's passphrase for a file that is simply truncated.
    # This is the same check decrypt_cesvu() already makes on cipher_body;
    # the streaming path could previously only tell empty from non-empty.
    if len(first_seg) < _SECRETSTREAM_ABYTES:
        segs.close()
        raise CesvuError(
            "TOO_SHORT",
            f"This file's ciphertext ({len(first_seg)} bytes) is shorter than the minimum "
            f"{_SECRETSTREAM_ABYTES}-byte secretstream MAC — it's truncated or corrupted."
            + PRODUCER_NONCONFORMANT,
        )

    def all_segments() -> Iterator[bytes]:
        """The peeked first segment, then the rest of the body."""
        try:
            yield first_seg
            for seg in segs:
                yield seg
        finally:
            segs.close()

    header_info = {

        "mode": parsed.mode,
        "kdf_memory_kib": parsed.kdf_memory_kib,
        "kdf_time_cost": parsed.kdf_time_cost,
        "pass_profile": parsed.pass_profile,
    }

    def plaintext_iter() -> Iterator[bytes]:
        # Derive INSIDE the generator so the key's whole lifetime is owned by
        # the try/finally below — see this function's docstring. A generator
        # that is created and never iterated does no Argon2id work and holds
        # no key; one that is closed mid-stream still reaches the wipe.
        key = derive_key_from_passphrase(
            pw_bytes,
            parsed.salt,
            parsed.kdf_memory_kib,
            parsed.kdf_time_cost,
            parsed.chunk_shift,
        )
        try:
            computed_key_check = compute_key_check(key)
            if not _constant_time_equal(computed_key_check, parsed.key_check):
                # Pre-authentication: a failed keyCheck and a tampered header
                # are deliberately indistinguishable here. Keep it that way.
                raise CesvuError(
                    "WRONG_PASSPHRASE_OR_HEADER_TAMPER",
                    "Wrong passphrase. Check the words or emoji and try again. (If you're sure "
                    "the passphrase is correct, the file may be corrupted or the producer is "
                    "non-conformant.)",
                )
            # Raises CesvuError('STREAM_HEADER_INVALID') on a malformed
            # streamHeader; backend failures propagate untouched.
            state = _init_pull(parsed.stream_header, key)
        except BaseException:
            _zero(bytearray(key))
            try:
                segs.close()
            except Exception:
                pass  # best-effort
            raise

        is_first = True
        tag_final_seen = False
        meta_buf = bytearray()
        metadata: Optional[CesvuMetadata] = None

        # Has ANY segment's MAC verified yet? Once one has, the passphrase is
        # cryptographically proven correct, so every later failure is file
        # corruption — never a bad password. This flag is what lets the errors
        # below tell the truth instead of blaming the passphrase for damage.
        authenticated = False

        body = all_segments()
        try:
            for seg in body:
                if len(seg) == 0:
                    continue
                ad = header_bytes if is_first else None
                result = _secretstream_pull(state, seg, ad)
                if not result:
                    # Split by whether anything has authenticated yet. Before
                    # the first successful pull this is genuinely ambiguous;
                    # after it, blaming the passphrase would be a lie.
                    if authenticated:
                        raise CesvuError(
                            "CIPHERTEXT_CORRUPT",
                            "This file is damaged: a chunk failed its authentication check "
                            "partway through. The passphrase is CORRECT (an earlier chunk "
                            "already verified with it), so re-entering it will not help — the "
                            "file itself has been altered or corrupted in transit/storage.",
                        )
                    raise CesvuError(
                        "WRONG_PASSPHRASE_OR_HEADER_TAMPER",
                        "Wrong passphrase. Check the words or emoji and try again. (If you're "
                        "sure the passphrase is correct, the file may be corrupted or the "
                        "producer is non-conformant.)",
                    )
                message, tag = result
                # This chunk's MAC verified, so the key — and therefore the
                # passphrase — is now proven correct.
                authenticated = True
                is_first = False
                _assert_tag_allowed(tag)
                if len(message) > 0:
                    if metadata is None:

                        meta_buf += message
                        try:
                            unpacked = unpack_metadata(bytes(meta_buf))
                            metadata = unpacked.meta
                            header_info["metadata"] = metadata
                            rest = bytes(meta_buf[unpacked.byte_len :])
                            meta_buf = bytearray()
                            if len(rest) > 0:
                                yield rest
                        except CesvuError as err:
                            if err.code == "METADATA_INCOMPLETE":
                                pass
                            elif err.code == "METADATA_CORRUPT":
                                # This segment's MAC already verified before we
                                # got here, so the passphrase is proven correct
                                # and the metadata is genuinely malformed.
                                raise CesvuError(
                                    "METADATA_CORRUPT_POST_AUTH",
                                    "This file's first chunk decrypted and authenticated "
                                    "correctly — the passphrase is CORRECT — but its embedded "
                                    "metadata is malformed." + PRODUCER_NONCONFORMANT,
                                ) from err
                            else:
                                raise
                    else:
                        yield message
                if tag == _TAG_FINAL:
                    tag_final_seen = True
                    break

            if tag_final_seen:
                for trailing in body:
                    if len(trailing) > 0:
                        # Only reachable after TAG_FINAL, so authentication has
                        # definitively succeeded. This is a malformed/appended
                        # file, never a passphrase problem.
                        raise CesvuError(
                            "TRAILING_DATA",
                            f"This file has {len(trailing)} unexpected bytes after its final "
                            f"chunk. Everything up to that point decrypted and authenticated "
                            f"correctly, so the passphrase is CORRECT — but data has been "
                            f"appended to the file." + PRODUCER_NONCONFORMANT,
                        )
            elif authenticated:
                # At least one chunk authenticated, so the key is right and the
                # stream simply stopped early: the file is truncated. Telling
                # the user to re-enter a passphrase that already worked would be
                # false AND would cost them another full Argon2id derivation.
                raise CesvuError(
                    "TRUNCATED",
                    "This file is incomplete: the encrypted stream ends without its final "
                    "chunk. The passphrase is CORRECT (earlier chunks decrypted successfully) "
                    "— the file itself was truncated, so re-entering the passphrase will not "
                    "help. Any data recovered from it is only a PREFIX of the original and "
                    "must not be treated as the whole file.",
                )
            else:
                # Nothing ever authenticated — genuinely ambiguous.
                raise CesvuError(
                    "WRONG_PASSPHRASE_OR_HEADER_TAMPER",
                    "The encrypted stream ended without a TAG_FINAL chunk — the file is "
                    "truncated or corrupted." + PRODUCER_NONCONFORMANT,
                )

            if metadata is None:
                # The stream ended (with a valid TAG_FINAL) before enough bytes
                # arrived to complete the metadata prefix. Authenticated, so
                # again: not a passphrase problem.
                raise CesvuError(
                    "METADATA_CORRUPT_POST_AUTH",
                    "This file decrypted and authenticated correctly — the passphrase is "
                    "CORRECT — but it ended before its metadata was complete."
                    + PRODUCER_NONCONFORMANT,
                )
        finally:
            # ORDER MATTERS: close the inner generator FIRST. If the CONSUMER
            # abandons this iterator early (breaks out of a for loop, drops the
            # last reference), our finally runs but the segment generator would
            # otherwise be left suspended — retaining the leftover buffer and
            # the underlying chunk iterator until GC happens to collect them.
            try:
                body.close()
            except Exception:
                pass  # best-effort
            _zero(bytearray(key))

    return DecryptStreamSession(plaintext_iter(), header_info)


