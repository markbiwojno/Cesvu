"""cesvu_crypto.py — Zero-knowledge export/import of a .cesvu v1 file.

This module is the Python mirror of src/lib/crypto/cesvu-crypto.ts. It MUST
stay byte-for-byte Acompatible with that file — see .cesvu SPEC/README.md for
the wire-format spec both implementations share. Any drift makes files
produced by one tool undecryptable by the other.

Stack (PyNaCl / libsodium bindings):
  - nacl.bindings.crypto_pwhash_alg (Argon2id13) for the KDF.
  - nacl.bindings.crypto_secretstream_xchacha20poly1305_* for streaming AEAD.
  - nacl.bindings.crypto_generichash_blake2b_salt_personal for domain
    separation (stream key) and keyCheck.
  - os.urandom for the CSPRNG.
"""

